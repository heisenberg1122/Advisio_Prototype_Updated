export function researchInterestsForProgram(
  programCode: string | null | undefined,
): readonly string[] {
  const normalized = programCode?.trim().toUpperCase() as VerifiedProgramCode;
  return RESEARCH_INTEREST_CATALOG[normalized] || [];
}

export function isResearchInterestForProgram(
  programCode: string | null | undefined,
  interest: string,
) {
  return researchInterestsForProgram(programCode).some(
    (candidate) => candidate === interest,
  );
}
