import type { ResearcherHelpTopic } from "./researcher-help";

export const deanCategories = [
  "College research",
  "Academic activities",
  "Communication and settings",
] as const;

type DeanCategory = (typeof deanCategories)[number];
const [research, academic, account] = deanCategories;

function help<Id extends `dean-${string}`>(
  id: Id,
  category: DeanCategory,
  href: string,
  question: string,
  keywords: string[],
  answer: string,
  target: string,
  permission?: string,
  fallback = "Check your active college, filters, and access if the page has no records.",
) {
  return {
    id,
    category,
    section: category,
    href,
    question,
    keywords,
    answer: [answer],
    target,
    permission,
    walkthrough: id,
    requirements: permission
      ? "An active Dean workspace, college assignment, and permission for this page are required."
      : "An active Dean workspace and college assignment are required.",
    fallback,
  } satisfies Omit<ResearcherHelpTopic, "id" | "walkthrough" | "category"> & {
    id: Id;
    walkthrough: Id;
    category: DeanCategory;
    target: string;
    permission?: string;
  };
}

